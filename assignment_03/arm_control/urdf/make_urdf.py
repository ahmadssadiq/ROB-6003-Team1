"""Write lekiwi.urdf, the robot description RViz needs, from the course's MuJoCo model.

RViz cannot read a MuJoCo file, so this converts models/LeKiwi-sim/mjcf_lcmm_robot.xml into a
URDF. Only the six arm joints can move in the result; the wheels are fixed. You only need to run
it again if the MuJoCo model changes:

    python make_urdf.py

The mesh paths in the URDF start with __MESH_DIR__. The launch file replaces that with the real
folder, so the URDF works wherever the course folder is.
"""
import math
import struct
from pathlib import Path

import mujoco
import numpy as np

import lekiwi_sim
from lekiwi_sim.simulator import MODEL_ARM_JOINTS, MODEL_BASE_BODY

MODEL_DIR = Path(lekiwi_sim.__file__).resolve().parent.parent / "models" / "LeKiwi-sim"
OUTPUT = Path(__file__).resolve().parent / "lekiwi.urdf"
MESH = mujoco.mjtGeom.mjGEOM_MESH


def rotation(quat):
    """MuJoCo quaternion (w, x, y, z) -> 3x3 rotation matrix."""
    matrix = np.zeros(9)
    mujoco.mju_quat2Mat(matrix, np.asarray(quat, float))
    return matrix.reshape(3, 3)


def rpy(matrix):
    """3x3 rotation matrix -> the roll, pitch, yaw angles URDF uses."""
    pitch = math.atan2(-matrix[2, 0], math.hypot(matrix[0, 0], matrix[1, 0]))
    if abs(matrix[2, 0]) > 1.0 - 1e-9:
        # Pitch is +-90 degrees: roll and yaw turn about the same line, so put it all in roll.
        return (math.atan2(-matrix[1, 2], matrix[1, 1]), pitch, 0.0)
    return (math.atan2(matrix[2, 1], matrix[2, 2]), pitch, math.atan2(matrix[1, 0], matrix[0, 0]))


def origin(position, matrix):
    r, p, y = rpy(matrix)
    x, y_, z = position
    return f'<origin xyz="{x:.6f} {y_:.6f} {z:.6f}" rpy="{r:.6f} {p:.6f} {y:.6f}"/>'


def stl_vertices(path):
    """All corner points of a binary STL file."""
    data = path.read_bytes()
    count = struct.unpack_from("<I", data, 80)[0]
    raw = np.frombuffer(data, dtype=np.dtype([("f", "<f4", 12), ("a", "<u2")]), count=count, offset=84)
    return raw["f"][:, 3:].reshape(-1, 3).astype(float)


def link_name(model, body):
    return model.body(body).name.replace(" ", "_")


def main():
    model = mujoco.MjModel.from_xml_path(str(MODEL_DIR / "mjcf_lcmm_robot.xml"))
    base = model.body(MODEL_BASE_BODY).id

    # Bodies that belong to the robot: the base body and everything attached to it.
    robot = [b for b in range(model.nbody) if b == base or _has_ancestor(model, b, base)]
    meshes_of = {b: [g for g in range(model.ngeom) if model.geom_bodyid[g] == b
                     and model.geom_type[g] == MESH and model.geom_contype[g] == 0] for b in robot}
    # Leave out bodies that would show nothing (the wheels' rollers).
    keep = [b for b in robot if any(meshes_of[d] for d in robot if d == b or _has_ancestor(model, d, b))]

    # A moving joint turns its body about the joint's anchor point. URDF needs the link's origin
    # to be that point, so each link frame is its body frame shifted to the anchor.
    arm_joint = {}
    for j in range(model.njnt):
        if model.joint(j).name in MODEL_ARM_JOINTS:
            arm_joint[model.jnt_bodyid[j]] = j
    shift = {b: (model.jnt_pos[arm_joint[b]].copy() if b in arm_joint else np.zeros(3)) for b in robot}

    out = ['<?xml version="1.0"?>',
           "<!-- Generated by make_urdf.py from the course's MuJoCo model. Do not edit by hand. -->",
           '<robot name="lekiwi">',
           # "base" is the course's base frame: x forward, y left, z up. The MuJoCo base body has
           # its front along +y, so it sits turned by -90 degrees inside "base".
           '  <link name="base"/>',
           f'  <joint name="base_to_model" type="fixed"><parent link="base"/>'
           f'<child link="{link_name(model, base)}"/><origin xyz="0 0 0" rpy="0 0 {-math.pi / 2:.6f}"/></joint>']

    for b in keep:
        out.append(f'  <link name="{link_name(model, b)}">')
        for g in meshes_of[b]:
            mesh = model.geom_dataid[g]
            file = Path(model.paths[model.mesh_pathadr[mesh]:].split(b"\0")[0].decode()).name
            # MuJoCo re-centres every mesh when it loads it. Undo that, so the original STL file
            # lands in the same place: point_in_geom = R_mesh^T (scale * point_in_file - p_mesh).
            r_mesh = rotation(model.mesh_quat[mesh])
            r_geom = rotation(model.geom_quat[g])
            position = model.geom_pos[g] - r_geom @ r_mesh.T @ model.mesh_pos[mesh] - shift[b]
            _check_mesh(model, mesh, MODEL_DIR / "meshes" / file, r_mesh)
            red, green, blue, alpha = model.geom_rgba[g]
            scale = " ".join(f"{s:g}" for s in model.mesh_scale[mesh])
            out += ["    <visual>",
                    "      " + origin(position, r_geom @ r_mesh.T),
                    f'      <geometry><mesh filename="file://__MESH_DIR__/{file}" scale="{scale}"/></geometry>',
                    f'      <material name="colour_{g}"><color rgba="{red:g} {green:g} {blue:g} {alpha:g}"/></material>',
                    "    </visual>"]
        out.append("  </link>")

        if b == base:
            continue
        parent = model.body_parentid[b]
        r_body = rotation(model.body_quat[b])
        position = model.body_pos[b] + r_body @ shift[b] - shift[parent]
        if b in arm_joint:
            j = arm_joint[b]
            low, high = model.jnt_range[j]
            axis = " ".join(f"{a:.6f}" for a in model.jnt_axis[j])
            out += [f'  <joint name="{model.joint(j).name}" type="revolute">',
                    f'    <parent link="{link_name(model, parent)}"/><child link="{link_name(model, b)}"/>',
                    "    " + origin(position, r_body),
                    f'    <axis xyz="{axis}"/>',
                    f'    <limit lower="{low:.5f}" upper="{high:.5f}" effort="10" velocity="5"/>',
                    "  </joint>"]
        else:
            out += [f'  <joint name="fixed_{link_name(model, b)}" type="fixed">',
                    f'    <parent link="{link_name(model, parent)}"/><child link="{link_name(model, b)}"/>',
                    "    " + origin(position, r_body),
                    "  </joint>"]

    out.append("</robot>")
    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"Wrote {OUTPUT} with {len(keep)} links and {len(arm_joint)} moving joints.")


def _has_ancestor(model, body, ancestor):
    while body != 0:
        body = model.body_parentid[body]
        if body == ancestor:
            return True
    return False


def _check_mesh(model, mesh, path, r_mesh):
    """Stop if undoing MuJoCo's re-centring does not give back the STL file's own points."""
    start, count = model.mesh_vertadr[mesh], model.mesh_vertnum[mesh]
    in_file = (model.mesh_vert[start:start + count] @ r_mesh.T + model.mesh_pos[mesh]) / model.mesh_scale[mesh]
    original = stl_vertices(path)
    error = max(np.abs(in_file.min(0) - original.min(0)).max(), np.abs(in_file.max(0) - original.max(0)).max())
    size = np.ptp(original, axis=0).max()
    if error > 1e-3 * size:
        raise SystemExit(f"{path.name}: mesh placement is off by {error:.4g} (mesh size {size:.4g})")


if __name__ == "__main__":
    main()
